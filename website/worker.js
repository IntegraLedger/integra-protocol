// The site's Worker. The exported site in out/ is its static assets; wrangler.toml runs this script first for page
// addresses and their .md addresses, and never for the build's files (scripts, the pages' RSC payloads, the Markdown
// copies, the LCP documents), so that a reader who asks for a page as Markdown gets the page's Markdown copy, which
// the build writes at /md/<page>.md:
//
//   GET /<page>.md, /index.md                 the page as Markdown (https://llmstxt.org)
//   GET /<page> with an Accept that ranks     the same Markdown, at the page's own address
//     text/markdown or text/x-markdown at
//     least as high as text/html, text/* and */*
//
// Every other request is answered by the static assets, which redirect a page address that ends in a slash to the
// address without it, whatever the Accept header asks for. A request carrying If-None-Match or another conditional
// header can be answered 304.
//
// Headers. Cloudflare's page on _headers (https://developers.cloudflare.com/workers/static-assets/headers/), as read on
// 2026-10-16, says: "Custom headers defined in the `_headers` file are not applied to responses generated by your
// Worker code, even if the request URL matches a rule defined in `_headers`. If you use a server-side rendered (SSR)
// framework, have configured `assets.run_worker_first`, or otherwise use a Worker script, you will likely need to
// attach any custom headers you wish to apply directly within that Worker script." Its page on run_worker_first
// (https://developers.cloudflare.com/workers/static-assets/binding/#run_worker_first) says: "You can also specify
// `run_worker_first` as an array of route patterns to selectively run the Worker script first only for specific
// routes." Neither says whether a response from `env.ASSETS.fetch` that the Worker returns carries _headers. So every
// response this Worker returns, a 200, a 304, a redirect or a 404, carries the headers out/_headers gives the address
// the reader asked for (the page or the .md address, not /md/…), each set to the rules' value in place of any value
// the static assets gave it. The build writes out/_headers into .worker/headers.mjs (scripts/worker-headers.mjs), and
// headers.mjs reads and matches the rules, as it does for every check. A response to a GET or HEAD whose answer the
// Accept header decides, at any address but a .md address or one that ends in a slash, also carries `Vary: Accept`.
import { isMarkdownPreferred } from "fumadocs-core/negotiation";
import HEADERS from "./.worker/headers.mjs";
import { headersFor, parseHeaders } from "./headers.mjs";

/** The rules of out/_headers. */
const RULES = parseHeaders(HEADERS);

/** The media types that ask for Markdown. `text/plain` is not one of them: it asks for any text. */
const MARKDOWN_TYPES = ["text/markdown", "text/x-markdown"];

/** The path of a page's Markdown copy: `/md/<page>.md`, and `/md/index.md` for the home page. */
function copyOf(page) {
  return page === "/" ? "/md/index.md" : `/md${page}.md`;
}

/** The page a .md address names: the home page for `/index.md`, `<page>` for `/<page>.md`, else none. */
function pageOf(pathname) {
  if (pathname === "/index.md") return "/";
  const page = pathname.slice(0, -".md".length);
  return page.endsWith("/") ? undefined : page;
}

/**
 * The page's Markdown copy as a 200 or 304 response, or undefined when the site holds no copy for that page. The
 * request's conditional headers go with it, so a copy the reader holds is answered 304.
 */
async function markdown(env, request, page) {
  const headers = new Headers();
  for (const [name, value] of request.headers) if (name.startsWith("if-")) headers.set(name, value);
  const response = await env.ASSETS.fetch(
    new Request(new URL(copyOf(page), request.url), { method: request.method, headers }),
  );
  return response.status === 200 || response.status === 304 ? response : undefined;
}

/**
 * The response with the headers out/_headers gives `address` set, and, when the Accept header decides the answer,
 * `Accept` added to its `Vary` header.
 */
function answer(response, address, varies) {
  const out = new Response(response.body, response);
  for (const [name, value] of Object.entries(headersFor(RULES, address))) out.headers.set(name, value);
  if (varies) {
    const vary = out.headers.get("Vary");
    if (vary === null) out.headers.set("Vary", "Accept");
    else if (!vary.split(",").some((v) => ["accept", "*"].includes(v.trim().toLowerCase()))) {
      out.headers.set("Vary", `${vary}, Accept`);
    }
  }
  return out;
}

export default {
  async fetch(request, env) {
    const { pathname } = new URL(request.url);
    const reads = request.method === "GET" || request.method === "HEAD";
    if (reads && pathname.endsWith(".md")) {
      const page = pageOf(pathname);
      const found = page === undefined ? undefined : await markdown(env, request, page);
      return answer(found ?? (await env.ASSETS.fetch(request)), pathname, false);
    }
    // At a page address, or one that could be, the Accept header decides the answer.
    const negotiates = reads && (pathname === "/" || !pathname.endsWith("/"));
    if (negotiates && isMarkdownPreferred(request, { markdownMediaTypes: MARKDOWN_TYPES })) {
      const found = await markdown(env, request, pathname);
      if (found !== undefined) return answer(found, pathname, true);
    }
    return answer(await env.ASSETS.fetch(request), pathname, negotiates);
  },
};
